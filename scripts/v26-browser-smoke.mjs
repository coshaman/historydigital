import { chromium } from 'playwright';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
console.log(JSON.stringify({ title: await page.title(), bodyStart: (await page.locator('body').innerText().catch(() => '')).slice(0, 240) }));
await page.evaluate(() => { localStorage.removeItem('chancery-gold-runtime-v1'); });
await page.reload({ waitUntil: 'networkidle' });
await page.locator('#ledgerObject').click();
const c01 = page.locator('[data-ledger-scene="C01"]');
if (!(await c01.count())) throw new Error('V26 ledger did not render C01');
console.log(JSON.stringify(await page.locator('[data-ledger-scene="C01"]').evaluate(el => ({ outer: el.outerHTML, hidden: el.closest('#ledgerOverlay')?.hidden, rect: el.getBoundingClientRect().toJSON(), onclick: String(el.onclick) }))));
await c01.click({ force: true });
if (!(await page.locator('.v25-pilot-excerpt-head').count())) await c01.dispatchEvent('click');
if (!(await page.locator('.v25-pilot-excerpt-head').count())) await page.evaluate(() => document.querySelector('[data-ledger-scene="C01"]').onclick());
console.log(JSON.stringify({ afterC01: (await page.locator('body').innerText()).slice(0, 900), pilotHeads: await page.locator('.v25-pilot-excerpt-head').count(), runtimeCase: await page.evaluate(() => window.__goldRuntime?.getState()?.caseId), lastRender: await page.evaluate(() => window.__goldRuntime?.getState()?.v26?.lastRenderCase), runtimeHasC01: await page.evaluate(() => window.__goldRuntime?.cases?.includes('C01')), v26Count: await page.evaluate(() => window.__goldRuntime?.getV26Manifest?.()?.cases?.length), pageErrors: errors }));
await page.locator('.v25-pilot-excerpt-head').first().click();
const excerptCount = await page.locator('.v25-pilot-excerpt-head').count();
for (let i = 1; i < excerptCount; i++) await page.locator('.v25-pilot-excerpt-head').nth(i).click();
if (!(await page.getByText('다섯 발췌를 읽고 처리 단계로 이동').count())) throw new Error('V26 C01 did not expose continue action');
await page.getByText('다섯 발췌를 읽고 처리 단계로 이동').click();
await page.locator('#choiceArea button').first().click();
await page.locator('#choiceArea button').first().click();
await page.locator('#choiceArea button').first().click();
const state = await page.evaluate(() => ({ caseId: window.__goldRuntime.getState().caseId, phase: window.__goldRuntime.getState().phase, v26: window.__goldRuntime.getState().v26, runtimeCases: window.__goldRuntime.cases.filter(id => /^C\d+$/.test(id)).length }));
await page.screenshot({ path: 'docs/v26/c01-browser-smoke.png', fullPage: true });
await browser.close();
if (errors.length) throw new Error(`page errors: ${errors.join('; ')}`);
console.log(JSON.stringify({ status: 'PASS', state, excerptCount, screenshot: 'docs/v26/c01-browser-smoke.png' }, null, 2));
